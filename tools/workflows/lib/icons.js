/**
 * Merge built-in icons with any custom icons from the workflow input.
 * Returns the merged object and a JS object-literal string for template injection.
 */
function buildIconsJs(customIcons) {
  const merged = Object.assign({}, ICONS, customIcons || {});
  const entries = Object.entries(merged)
    .map(([k, v]) => `  ${k}:${JSON.stringify(v)}`)
    .join(',\n');
  return `{\n${entries}\n}`;
}

